import 'dart:async';

import '../../../../core/constants/app_constants.dart';
import '../../domain/entities/ai_reply.dart';
import '../../domain/entities/ai_stream_event.dart';
import '../../domain/entities/ai_task.dart';
import '../dto/ai_request_dto.dart';
import 'ai_data_source.dart';

/// Offline sample data source used only when the app is explicitly built with
/// `--dart-define=AI_USE_MOCK=true`.
///
/// It never pretends to be a real model: every reply states that demo mode is
/// active, and no usage numbers are reported. The UI also shows a persistent
/// "Demo mode" banner. See `README.md`.
class MockAiDataSource implements AiDataSource {
  MockAiDataSource({this.chunkDelay = const Duration(milliseconds: 40)});

  /// Delay between streamed chunks. Set to [Duration.zero] in tests.
  final Duration chunkDelay;

  @override
  Future<AiReply> complete(AiRequestDto request) async {
    await Future<void>.delayed(chunkDelay);
    return AiReply(text: _compose(request), model: 'demo-sample');
  }

  @override
  Stream<AiStreamEvent> stream(AiRequestDto request) async* {
    final text = _compose(request);
    final chunks = _chunk(text);

    for (final chunk in chunks) {
      if (chunkDelay > Duration.zero) {
        await Future<void>.delayed(chunkDelay);
      } else {
        await Future<void>.delayed(Duration.zero);
      }
      yield AiStreamDelta(chunk);
    }
    yield AiStreamCompleted(AiReply(text: text, model: 'demo-sample'));
  }

  /// Splits text into word-sized pieces to exercise the streaming UI.
  List<String> _chunk(String text) {
    final pieces = <String>[];
    final matches = RegExp(r'\S+\s*').allMatches(text);
    for (final match in matches) {
      pieces.add(match.group(0)!);
    }
    return pieces.isEmpty ? [text] : pieces;
  }

  String _compose(AiRequestDto request) {
    final isKhmer = request.locale == AppConstants.kmLanguageCode;
    final preview = _preview(
      request.task == AiTask.chat
          ? (request.messages.isEmpty
                ? ''
                : request.messages.last.content)
          : (request.input ?? ''),
    );

    if (isKhmer) {
      final header = _khmerHeader(request.task);
      return '⚠️ របៀបសាកល្បង (Demo mode)\n\n'
          '$header\n\n'
          'អត្ថបទដែលអ្នកបានផ្ញើ៖ «$preview»\n\n'
          'នេះគឺជាចម្លើយគំរូសម្រាប់សាកល្បងកម្មវិធី មិនមែនចម្លើយពី AI ពិតប្រាកដទេ។ '
          'សូមកំណត់ AI_BASE_URL ដើម្បីភ្ជាប់ទៅម៉ាស៊ីនមេ AI ពិតប្រាកដ។';
    }

    final header = _englishHeader(request.task);
    return '⚠️ Demo mode\n\n'
        '$header\n\n'
        'Your input: "$preview"\n\n'
        'This is a built-in sample reply used to preview the app. It is not '
        'generated by a real AI model. Set AI_BASE_URL to connect a real '
        'backend.';
  }

  String _khmerHeader(AiTask task) => switch (task) {
    AiTask.chat => 'ខ្ញុំជាជំនួយការ AI ខ្មែរ។',
    AiTask.translate => 'លទ្ធផលបកប្រែគំរូ៖',
    AiTask.improveWriting => 'សេចក្ដីព្រាងគំរូរបស់អ្នក៖',
    AiTask.summarize => 'សេចក្ដីសង្ខេបគំរូ៖',
    AiTask.explainEnglish => 'ការពន្យល់គំរូ៖',
  };

  String _englishHeader(AiTask task) => switch (task) {
    AiTask.chat => 'I am the Khmer AI Assistant.',
    AiTask.translate => 'Sample translation:',
    AiTask.improveWriting => 'Your sample draft:',
    AiTask.summarize => 'Sample summary:',
    AiTask.explainEnglish => 'Sample explanation:',
  };

  String _preview(String text) {
    final normalized = text.trim().replaceAll(RegExp(r'\s+'), ' ');
    if (normalized.isEmpty) return '…';
    if (normalized.length <= 120) return normalized;
    return '${normalized.substring(0, 120)}…';
  }
}
